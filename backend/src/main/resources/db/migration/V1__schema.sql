-- Schema is intentionally portable: it must run on PostgreSQL AND H2 (PostgreSQL mode).
-- No JSONB, no SERIAL, no partial indexes.

CREATE TABLE users (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    organization  VARCHAR(160),
    admin_level   INTEGER,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('backer', 'creator', 'admin'))
);

CREATE TABLE categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80) NOT NULL,
    CONSTRAINT uq_categories_name UNIQUE (name)
);

CREATE TABLE campaigns (
    campaign_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(200) NOT NULL,
    description    TEXT NOT NULL,
    goal_amount    NUMERIC(14, 2) NOT NULL,
    duration_days  INTEGER NOT NULL,
    country        VARCHAR(2) NOT NULL,
    category_id    BIGINT NOT NULL,
    creator_id     BIGINT NOT NULL,
    status         VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    pledged_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    backer_count   INTEGER NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE,
    ends_at        TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_campaigns_category FOREIGN KEY (category_id) REFERENCES categories (category_id),
    CONSTRAINT fk_campaigns_creator FOREIGN KEY (creator_id) REFERENCES users (user_id),
    CONSTRAINT ck_campaigns_status CHECK (status IN ('DRAFT', 'SUBMITTED'))
);

CREATE INDEX idx_campaigns_status ON campaigns (status);
CREATE INDEX idx_campaigns_creator ON campaigns (creator_id);
CREATE INDEX idx_campaigns_category ON campaigns (category_id);

CREATE TABLE rewards (
    reward_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL,
    title       VARCHAR(160),
    description VARCHAR(500) NOT NULL,
    min_pledge  NUMERIC(14, 2) NOT NULL,
    quantity    INTEGER,
    CONSTRAINT fk_rewards_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns (campaign_id) ON DELETE CASCADE
);

CREATE INDEX idx_rewards_campaign ON rewards (campaign_id);

CREATE TABLE datasets (
    dataset_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name      VARCHAR(255) NOT NULL,
    storage_path   VARCHAR(500) NOT NULL,
    row_count      INTEGER NOT NULL DEFAULT 0,
    feature_count  INTEGER NOT NULL DEFAULT 0,
    status         VARCHAR(20) NOT NULL DEFAULT 'validated',
    uploaded_by_id BIGINT,
    uploaded_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_datasets_uploader FOREIGN KEY (uploaded_by_id) REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT ck_datasets_status CHECK (status IN ('validated', 'processing', 'archived'))
);

CREATE TABLE model_versions (
    version_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    algorithm       VARCHAR(40) NOT NULL,
    name            VARCHAR(120) NOT NULL,
    version         VARCHAR(20) NOT NULL,
    accuracy        DOUBLE PRECISION NOT NULL DEFAULT 0,
    f1_score        DOUBLE PRECISION NOT NULL DEFAULT 0,
    precision_score DOUBLE PRECISION,
    recall          DOUBLE PRECISION,
    roc_auc         DOUBLE PRECISION,
    dataset_id      BIGINT,
    hyperparameters TEXT,
    artifact_path   VARCHAR(500),
    is_active       BOOLEAN NOT NULL DEFAULT FALSE,
    training_status VARCHAR(20) NOT NULL DEFAULT 'ready',
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_models_dataset FOREIGN KEY (dataset_id) REFERENCES datasets (dataset_id),
    CONSTRAINT ck_models_algorithm CHECK (algorithm IN ('LogisticRegression', 'RandomForest', 'XGBoost')),
    CONSTRAINT ck_models_training_status CHECK (training_status IN ('training', 'ready', 'failed'))
);

CREATE INDEX idx_models_active ON model_versions (is_active);
CREATE INDEX idx_models_dataset ON model_versions (dataset_id);

CREATE TABLE pledges (
    pledge_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    campaign_id BIGINT NOT NULL,
    reward_id   BIGINT,
    amount      NUMERIC(14, 2) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pledges_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_pledges_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns (campaign_id) ON DELETE CASCADE,
    CONSTRAINT fk_pledges_reward FOREIGN KEY (reward_id) REFERENCES rewards (reward_id) ON DELETE SET NULL
);

CREATE INDEX idx_pledges_user ON pledges (user_id);
CREATE INDEX idx_pledges_campaign ON pledges (campaign_id);

CREATE TABLE predictions (
    prediction_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id      BIGINT NOT NULL,
    model_version_id BIGINT,
    probability      DOUBLE PRECISION NOT NULL,
    label            VARCHAR(40) NOT NULL,
    top_factors      TEXT,
    explanation      VARCHAR(1000),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_predictions_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns (campaign_id) ON DELETE CASCADE,
    CONSTRAINT fk_predictions_model FOREIGN KEY (model_version_id) REFERENCES model_versions (version_id) ON DELETE SET NULL,
    CONSTRAINT ck_predictions_label CHECK (label IN ('Likely Success', 'Likely Fail'))
);

CREATE INDEX idx_predictions_campaign ON predictions (campaign_id);
CREATE INDEX idx_predictions_created ON predictions (created_at);
